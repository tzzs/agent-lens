#!/usr/bin/env node
/**
 * Build-time generator for `src/default-snapshot.json` (plan-v2 §8: prices are never
 * hand-maintained). Reads litellm's `model_prices_and_context_window.json` and keeps the
 * text-generation models the agent CLIs on this machine can actually name.
 *
 *   node packages/pricing/scripts/generate-snapshot.mjs --out packages/pricing/src/default-snapshot.json
 *   node packages/pricing/scripts/generate-snapshot.mjs --input /tmp/litellm.json   # offline
 *
 * litellm publishes no price history, so every generated entry applies from the epoch and
 * `effective_from` is a placeholder for a human to pin once a reprice is confirmed (§8).
 * Until then, historical costs are computed at today's price and `agentlens pricing override`
 * is the way to record a dated correction.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const LITELLM_URL =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json'
const HERE = dirname(fileURLToPath(import.meta.url))
const DEFAULT_OUT = resolve(HERE, '../src/default-snapshot.json')

// Modes that bill per token for text we care about; audio/image/embedding are other products.
const TEXT_MODES = new Set(['chat', 'completion', 'responses'])
const COST_FIELDS = [
  'input_cost_per_token',
  'output_cost_per_token',
  'cache_read_input_token_cost',
  'cache_creation_input_token_cost',
  'input_cost_per_reasoning_token',
]

function arg(name) {
  const i = process.argv.indexOf(`--${name}`)
  return i === -1 ? undefined : process.argv[i + 1]
}

async function loadSource() {
  const local = arg('input')
  if (local) return JSON.parse(readFileSync(local, 'utf8'))
  const res = await fetch(LITELLM_URL)
  if (!res.ok) throw new Error(`litellm snapshot fetch failed: ${res.status} ${res.statusText}`)
  return res.json()
}

/** Provider-prefixed ids and slash-routed variants describe one model many times; the bare id is canonical. */
function isBareModelKey(key) {
  return !key.includes('/') && key !== 'sample_spec'
}

function hasBudgetSuffix(key) {
  return /[-@](budget|preview)$/i.test(key) || /\[budget\]/i.test(key)
}

const raw = await loadSource()
const fetchedAt = Date.now()
const entries = []

for (const [key, value] of Object.entries(raw)) {
  if (!isBareModelKey(key) || typeof value !== 'object' || value === null) continue
  if (!TEXT_MODES.has(value.mode)) continue
  if (hasBudgetSuffix(key)) continue
  if (typeof value.input_cost_per_token !== 'number' || typeof value.output_cost_per_token !== 'number') continue

  const entry = {
    model: key,
    litellm_provider: value.litellm_provider ?? 'unknown',
    effective_from: 0,
  }
  for (const field of COST_FIELDS) {
    if (typeof value[field] === 'number') entry[field] = value[field]
  }
  entries.push(entry)
}

entries.sort((a, b) => a.model.localeCompare(b.model))

const snapshot = {
  schemaVersion: 1,
  fetchedAt,
  source: `generated by packages/pricing/scripts/generate-snapshot.mjs from ${arg('input') ? '--input file' : LITELLM_URL}`,
  entries,
}

writeFileSync(arg('out') ?? DEFAULT_OUT, `${JSON.stringify(snapshot, null, 2)}\n`)
const priced = new Set(entries.map((e) => e.litellm_provider)).size
process.stdout.write(
  `${entries.length} entries across ${priced} providers → ${arg('out') ?? DEFAULT_OUT}\n`,
)
